package com.lisovskyi.core_service.audit_log.enums;

// USER - зміну ухвалила людина, changed_by тоді NOT NULL і показує на реальний auth.users.id.
//
// SYSTEM - зміну спричинив автоматичний процес, за який не відповідає жодна конкретна людина
// (напр. перерахунок dueOn при зміні виробничого календаря - DeadlineListener/SEN-26), тому
// changed_by = null. Свідомо НЕ заводимо для цього фіктивний рядок в auth.users - changed_by
// лишається чесним soft-ref на реального користувача, коли він не null, а не полем, куди можна
// підсунути вигаданий id.
//
// Коли Go-сервіси отримають SERVICE-роль токена з власною ідентичністю виклику (SEN-33, ще не
// реалізовано), для їхніх змін матиме сенс окреме значення SERVICE замість SYSTEM - але заводити
// його зараз нема від чого відштовхнутись.
public enum ChangedByType {
    USER,
    SYSTEM
}
