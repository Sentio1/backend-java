package com.lisovskyi.core_service.case_event.enums;

// SEN-29 AC2: явний видимий стан "чи ця подія має строк", щоб картка справи не здогадувалась
// по порожньому/непорожньому deadlineIds - і щоб REJECTED (SEN-29 AC4) не виглядав так само,
// як "нема жодного застосовного правила" (обидва раніше давали однаково порожній список).
public enum DeadlineResolution {
    // Є хоча б один невідхилений дедлайн - подія породила строк(и) як очікувалось.
    RULE_APPLIED,
    // Жодне DeadlineRule не підійшло під (procedure, eventCode, instance, дата) - подія
    // збережена, але юрист має додати строк вручну (AC3).
    NO_RULE_MATCHED,
    // Дедлайн(и) були розраховані, але юрист відхилив усі з причиною (AC4) - на відміну від
    // NO_RULE_MATCHED, тут система порахувала, просто юрист вирішив, що строк не застосовний.
    REJECTED
}
