-- ═══════════════════════════════════════════════════════════
-- Міграція: унікальність registry_document_id у case_events (SEN-19)
-- ═══════════════════════════════════════════════════════════
-- Го-воркер поллить ЄДРСР періодично й може прислати той самий документ
-- удруге - без індексу другий поллінг створює дубль CaseEvent.
--
-- Унікальність - у межах справи, а не глобальна: той самий документ реєстру
-- цілком легітимно може прилетіти в кілька case_events різних органзацій/справ
-- (позивач і відповідач можуть бути клієнтами різних юридичних бюро й обидва
-- моніторити ту саму справу в ЄДРСР) - глобальний унікальний індекс на
-- registry_document_id заблокував би другій організації валідну подію.
--
-- Частковий індекс: лише REGISTRY-джерело, лише активні (не видалені) рядки,
-- лише коли registry_document_id заповнений (для MANUAL він завжди NULL,
-- а NULL в унікальному індексі Postgres не конфліктує сам із собою і без
-- предиката IS NOT NULL).
CREATE UNIQUE INDEX uq_case_events_case_registry_document
    ON core.case_events (case_id, registry_document_id)
    WHERE source = 'REGISTRY' AND deleted_at IS NULL AND registry_document_id IS NOT NULL;
