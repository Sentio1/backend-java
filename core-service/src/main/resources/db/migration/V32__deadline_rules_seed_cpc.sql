-- Перша версія (version = 1) кожного правила, чинна з 15.12.2017 - дати набрання
-- чинності редакцією ЦПК України, запровадженою процесуальною реформою 2017 року
-- (Закон №2147-VIII), на якій засновані номери статей і строки нижче.
--
-- УВАГА, юридична застереження: це чотири найчастіше цитовані строки ЦПК (відзив,
-- відповідь на відзив, апеляція, касація) для демонстрації того, як version/instance
-- працюють разом - а НЕ вичерпний довідник і НЕ заміна юридичної звірки. Кожен рядок
-- (номер статті, кількість днів, calendar/working, is_extendable) має перевірити юрист
-- перед продом - помилка тут має дисциплінарні наслідки (див. контекст SEN-24, SEN-74).
--
-- Окрема, конкретна відома неточність (SEN-74): CPC_APPEAL_ON_DECISION/CPC_CASSATION_APPEAL
-- (ст. 354/390) - строки, зафіксовані законом (30 днів), тут duration_value = фактичний
-- застосовний строк. А CPC_STATEMENT_OF_DEFENCE/CPC_RESPONSE_TO_DEFENCE (ст. 178/179) -
-- НЕ фіксовані строки: суд сам встановлює конкретний строк в ухвалі про відкриття
-- провадження, ст.178 задає лише МІНІМУМ ("не менше 15 днів"), ст.179 - лише МАКСИМУМ
-- ("не більше 5 днів"). Схема deadline_rules не має способу відрізнити "фіксований
-- законом строк" від "законна межа, у якій суд призначає власне число" - duration_value
-- тут це межа (15/5), видана за фактичний строк. Це прийнятне спрощення для першої версії
-- лише якщо юрист (SEN-74) підтвердить: або продукт свідомо рахує "по мінімуму/максимуму"
-- і це задокументовано для користувача, або перед продом деталізуємо схему (наприклад,
-- окремий прапорець "суд може подовжити/скоротити" замість трактування межі як факту).
--
-- CPC_APPEAL_ON_DECISION (instance=FIRST) і CPC_CASSATION_APPEAL (instance=APPEAL)
-- навмисно ділять один trigger_event_code (DECISION) - без колонки instance (V30)
-- findByActiveRule(procedure, triggerEventCode, instance, date) не міг би розрізнити,
-- яке з двох правил чинне.
--
